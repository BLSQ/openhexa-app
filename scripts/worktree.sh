#!/usr/bin/env bash
# Extra checkouts of OpenHEXA (git worktrees), each opened in its own IDE window
# and running its own app, to work on or test several branches at once.
#
#   make worktree            create the next one, ../openhexa-app-<N>, and open it in
#                            the IDE whose terminal runs it
#   make worktree-reset-db   reset an extra checkout's database from the main one
#   make worktree-remove     remove an extra checkout, its containers and database
#
# The last two act on the extra checkout they run in, or ask which one when run
# from the main checkout.
#
# Inside an extra checkout, switch branches (`git checkout -b ...`) and run the
# app (`make rbl`, `make rf`) as usual: its .env holds its ports and compose project.
#
# Extra checkout N gets its own ports (backend 8000+10N, frontend 3000+10N), its
# own hostname openhexa-app-<N>.localhost, so that its login cookies do not clash with the
# other checkouts (cookies ignore the port), and its own copy of the app
# database. The postgres server, Forgejo, MailHog and workspace files are the
# main checkout's.

set -euo pipefail

MAIN_DIR="$(cd "$(dirname "$(git rev-parse --path-format=absolute --git-common-dir)")" && pwd)"
MAIN_DB_PORT="${OPENHEXA_MAIN_DB_PORT:-5434}"
MAX_N=9

info() {
  echo "→ $*" >&2
}

fail() {
  echo "Error: $*" >&2
  exit 1
}

env_get() { # file key
  [[ -f "$1" ]] && sed -n "s/^$2=//p" "$1" | tail -n1 || true
}

env_set() { # file key value
  if grep -q "^$2=" "$1"; then
    # `|` as delimiter: values contain slashes, never pipes
    sed -i.bak "s|^$2=.*|$2=$3|" "$1" && rm -f "$1.bak"
  else
    printf '%s=%s\n' "$2" "$3" >>"$1"
  fi
}

main_compose() {
  (cd "$MAIN_DIR" && docker compose "$@")
}

extra_checkouts() {
  local dir
  for dir in $(git -C "$MAIN_DIR" worktree list --porcelain | sed -n 's/^worktree //p'); do
    [[ -n "$(env_get "$dir/.env" WORKTREE_N)" ]] && echo "$dir"
  done
  return 0
}

# The extra checkout the command runs in or, from the main checkout (whose
# Makefile has these commands even when the extra checkout's branch does not),
# the one the user picks.
target_checkout() {
  local dir checkouts
  dir=$(git rev-parse --show-toplevel)
  if [[ "$dir" != "$MAIN_DIR" ]]; then
    [[ -n "$(env_get "$dir/.env" WORKTREE_N)" ]] || fail "$dir was not created by \`make worktree\`"
    echo "$dir"
    return
  fi
  checkouts=($(extra_checkouts))
  case ${#checkouts[@]} in
    0) fail "there is no extra checkout, create one with \`make worktree\`" ;;
    1) echo "${checkouts[0]}" ;;
    *)
      PS3="Which checkout? "
      select dir in "${checkouts[@]}"; do
        [[ -n "$dir" ]] && { echo "$dir"; return; }
      done
      exit 1
      ;;
  esac
}

start_main_services() {
  docker network inspect openhexa >/dev/null 2>&1 || docker network create openhexa >/dev/null
  main_compose up -d --wait db forgejo mailhog >&2
}

write_env() { # dir n
  local dir=$1 n=$2 env="$1/.env"
  local backend_port=$((8000 + n * 10)) frontend_port=$((3000 + n * 10)) host="$(basename "$dir").localhost"
  # From the main checkout, so that branches older than the overlay still run
  local compose_file="docker-compose.yaml:$MAIN_DIR/docker-compose.worktree.yaml"

  [[ -f "$MAIN_DIR/.env" ]] || fail "$MAIN_DIR/.env is missing, set up the main checkout first"
  cp "$MAIN_DIR/.env" "$env"
  if [[ -f "$MAIN_DIR/docker-compose.override.yaml" ]]; then
    cp "$MAIN_DIR/docker-compose.override.yaml" "$dir/"
    compose_file+=":docker-compose.override.yaml"
  fi
  printf '\n# Extra checkout, generated by scripts/worktree.sh\n' >>"$env"
  env_set "$env" WORKTREE_N "$n"
  env_set "$env" COMPOSE_PROJECT_NAME "$(basename "$dir")"
  env_set "$env" COMPOSE_FILE "$compose_file"
  env_set "$env" BASE_HOSTNAME "$host"
  env_set "$env" BASE_PORT "$backend_port"
  env_set "$env" FRONTEND_PORT "$frontend_port"
  # Read by the frontend dev server (frontend/server/index.mjs)
  env_set "$env" PORT "$frontend_port"
  env_set "$env" OPENHEXA_BACKEND_URL "http://localhost:$backend_port"
  # Pipeline containers reach the backend through the host
  env_set "$env" INTERNAL_BASE_URL "http://host.docker.internal:$backend_port"
  env_set "$env" WEBAPPS_DOMAIN "webapps.$host:$backend_port"
  # So that web apps also show when the frontend is opened on localhost
  env_set "$env" WEBAPPS_ADDITIONAL_FRAME_ANCESTORS "http://localhost:$frontend_port"
  env_set "$env" DATABASE_HOST host.docker.internal
  env_set "$env" DATABASE_PORT "$MAIN_DB_PORT"
  env_set "$env" DATABASE_NAME "$(env_get "$MAIN_DIR/.env" DATABASE_NAME)-$n"
  env_set "$env" WORKSPACES_DATABASE_HOST host.docker.internal
  env_set "$env" WORKSPACES_DATABASE_PORT "$MAIN_DB_PORT"
  env_set "$env" EMAIL_HOST host.docker.internal
  env_set "$env" GIT_SERVER_URL http://host.docker.internal:3100

  if [[ -f "$MAIN_DIR/frontend/.env" ]]; then
    cp "$MAIN_DIR/frontend/.env" "$dir/frontend/.env"
    env_set "$dir/frontend/.env" OPENHEXA_BACKEND_URL "http://localhost:$backend_port"
  fi
}

copy_database() { # dir
  local source target
  source=$(env_get "$MAIN_DIR/.env" DATABASE_NAME)
  target=$(env_get "$1/.env" DATABASE_NAME)
  start_main_services
  info "Copying database $source into $target"
  # pg_dump rather than CREATE DATABASE ... TEMPLATE: the latter fails while the
  # main app holds connections to the source database.
  main_compose exec -T db bash -euo pipefail -c '
    PGOPTIONS="-c client_min_messages=warning" psql -q -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" -d postgres \
      -c "DROP DATABASE IF EXISTS \"$1\" WITH (FORCE)" \
      -c "CREATE DATABASE \"$1\" TEMPLATE template0"
    pg_dump -U "$POSTGRES_USER" "$0" | psql -q -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" -d "$1" >/dev/null
  ' "$source" "$target"
}

# Starting from the main checkout's images avoids a build; a rebuild in the extra
# checkout (e.g. new dependency) only replaces its own tags.
tag_images() { # project
  local service source
  for service in app dataset_worker workspace_copy_worker pipelines_runner pipelines_scheduler; do
    source="$(basename "$MAIN_DIR")-$service"
    [[ $service == app ]] && source=blsq/openhexa-app
    if docker image inspect "$source" >/dev/null 2>&1 && ! docker image inspect "$1-$service" >/dev/null 2>&1; then
      docker tag "$source" "$1-$service"
    fi
  done
}

# Opens the checkout in the IDE whose terminal runs this (macOS sets the bundle id
# of the app a terminal runs in); from a standalone terminal, opens nothing.
open_ide() { # dir
  if [[ "${TERMINAL_EMULATOR:-}" == JetBrains* || "${TERM_PROGRAM:-}" == vscode ]] && [[ -n "${__CFBundleIdentifier:-}" ]]; then
    open -nb "$__CFBundleIdentifier" --args "$1"
  fi
}

cmd_new() {
  local n dir
  for ((n = 2; n <= MAX_N; n++)); do
    dir="$MAIN_DIR-$n"
    # An IDE window left open on a removed checkout writes its .idea back
    if [[ -d "$dir/.idea" && -z "$(ls -A "$dir" | grep -vx .idea)" ]]; then
      rm -r "$dir/.idea"
      rmdir "$dir"
    fi
    [[ -e "$dir" ]] || break
  done
  ((n <= MAX_N)) || fail "../$(basename "$MAIN_DIR")-2 to -$MAX_N are all taken"

  git -C "$MAIN_DIR" fetch --quiet origin main || info "Could not fetch origin/main, using the last fetched one"
  info "Creating $dir on origin/main"
  # Detached, so that any branch can then be checked out in it, main included
  git -C "$MAIN_DIR" worktree add --quiet --detach "$dir" origin/main
  write_env "$dir" "$n"
  # Interpreter and run configurations; workspace.xml only holds window state.
  [[ -d "$MAIN_DIR/.idea" ]] && rsync -a --exclude workspace.xml --exclude shelf "$MAIN_DIR/.idea/" "$dir/.idea/"
  copy_database "$dir"
  tag_images "$(basename "$dir")"
  info "Installing the frontend dependencies"
  npm --prefix "$dir/frontend" install --prefer-offline --no-audit --no-fund --loglevel=error
  open_ide "$dir"
  cat >&2 <<EOF

$dir is ready: switch branches there as usual and run \`make dev\`
http://$(basename "$dir").localhost:$((3000 + n * 10))
When you are done with it: \`make worktree-remove\`
EOF
}

cmd_db() {
  local dir
  dir=$(target_checkout)
  copy_database "$dir"
  info "Done. Restart the backend if it is running."
}

cmd_remove() {
  local dir db branch
  dir=$(target_checkout)
  db=$(env_get "$dir/.env" DATABASE_NAME)
  branch=$(git -C "$dir" branch --show-current)
  read -r -p "Remove $dir, including uncommitted changes, and its database $db? [y/N] " answer
  [[ $answer == [yY] ]] || exit 1

  if [[ -n "$(cd "$dir" && docker compose ps -aq)" ]]; then
    info "Stopping its containers"
    (cd "$dir" && docker compose --progress quiet --profile '*' down --remove-orphans) || true
  fi
  docker image ls --format '{{.Repository}}' | grep "^$(basename "$dir")-" | xargs docker image rm >/dev/null 2>&1 || true
  info "Dropping its database $db"
  main_compose exec -T db bash -c 'psql -q -U "$POSTGRES_USER" -d postgres -c "DROP DATABASE IF EXISTS \"$0\" WITH (FORCE)"' "$db" || true

  info "Deleting $dir (takes a minute because of node_modules)"
  git -C "$MAIN_DIR" worktree remove --force "$dir"

  info "Done."
  if [[ -n "$branch" ]]; then
    echo "The branch $branch still exists in the repository; once merged, delete it with: git branch -D $branch" >&2
  fi
}

case "${1:-}" in
  new) cmd_new ;;
  db) cmd_db ;;
  remove) cmd_remove ;;
  *) echo "Usage: scripts/worktree.sh new | db | remove" >&2; exit 1 ;;
esac
